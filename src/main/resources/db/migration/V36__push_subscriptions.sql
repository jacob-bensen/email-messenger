-- Web Push subscriptions the client registered with a push service
-- (Firebase / Mozilla / Apple). endpoint is the opaque push-service URL
-- the server POSTs the encrypted payload to; the two keys are the RFC 8291
-- material used to encrypt that payload for this specific subscription.
CREATE TABLE push_subscriptions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    endpoint     VARCHAR(2000) NOT NULL,
    p256dh_key   VARCHAR(255) NOT NULL,
    auth_key     VARCHAR(255) NOT NULL,
    user_agent   VARCHAR(500),
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMP,
    CONSTRAINT uk_push_subscriptions_user_endpoint UNIQUE (user_id, endpoint)
);

CREATE INDEX idx_push_subscriptions_user ON push_subscriptions(user_id);
