-- Bearer tokens for the mobile client's REST API (/api/v1/**).
--
-- Only the SHA-256 of the opaque token is stored, so a database leak
-- doesn't yield usable credentials; the raw value is returned once, at
-- login. `revoked_at` is set by logout; `expires_at` bounds a token that
-- is never explicitly revoked. `last_used_at` is informational (a future
-- "signed-in devices" list on /account).
CREATE TABLE api_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    token_hash   VARCHAR(64)  NOT NULL,
    device_name  VARCHAR(100),
    created_at   TIMESTAMP    NOT NULL,
    expires_at   TIMESTAMP    NOT NULL,
    last_used_at TIMESTAMP,
    revoked_at   TIMESTAMP,
    CONSTRAINT fk_api_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_api_tokens_hash UNIQUE (token_hash)
);

CREATE INDEX idx_api_tokens_user ON api_tokens (user_id);
