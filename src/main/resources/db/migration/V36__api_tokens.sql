-- Bearer tokens for the mobile client's /api/v1/** surface.
--
-- Same shape as password_reset_tokens: the plaintext token (32 random
-- bytes → URL-safe base64, prefixed with "cmxo_") is returned to the
-- caller once at issue time and never persisted. token_hash is
-- SHA-256(plaintext) hex so a full table dump can't be replayed.
--
-- Tokens do not expire on the server in v1; they are revoked when the
-- user signs out (POST /api/v1/auth/logout sets revoked_at). last_used_at
-- is updated on every successful lookup so /account can surface stale
-- sessions in a future revision.
CREATE TABLE api_tokens (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL,
    token_hash    VARCHAR(64)  NOT NULL,
    user_agent    VARCHAR(255),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at  TIMESTAMP,
    revoked_at    TIMESTAMP,
    CONSTRAINT fk_api_token_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_api_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_api_token_user ON api_tokens (user_id);
