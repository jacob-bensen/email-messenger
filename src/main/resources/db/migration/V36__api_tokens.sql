-- Bearer tokens for the mobile client's REST API (/api/v1/**).
--
-- The browser keeps using the session cookie; the app can't (no CSRF
-- form round-trip, no cookie jar worth trusting), so POST
-- /api/v1/auth/login mints an opaque random token instead. Only
-- SHA-256(token) is stored, same as password_reset_tokens, so a table
-- dump can't be replayed. A token dies when it expires, when the app
-- logs out (revoked_at), or when the user's password changes (every
-- live token for the user is revoked).
CREATE TABLE api_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    token_hash   VARCHAR(64)  NOT NULL,
    device_name  VARCHAR(100),
    expires_at   TIMESTAMP    NOT NULL,
    revoked_at   TIMESTAMP,
    last_used_at TIMESTAMP,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_api_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_api_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_api_tokens_user ON api_tokens (user_id);
