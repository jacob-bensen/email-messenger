-- Bearer tokens for the mobile REST API (/api/v1). The plaintext token
-- (32 random bytes, URL-safe base64) is returned once from
-- POST /api/v1/auth/login and never stored; we keep SHA-256(token) as
-- 64-char hex, same as password_reset_tokens, so a table dump can't be
-- replayed. Logout stamps revoked_at; expiry is enforced in the service.
CREATE TABLE api_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    token_hash VARCHAR(64)  NOT NULL,
    expires_at TIMESTAMP    NOT NULL,
    revoked_at TIMESTAMP,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_api_token_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_api_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_api_token_user ON api_tokens (user_id);
