-- Bearer tokens for the mobile client's /api/v1 (docs/API.md §2).
--
-- Like password_reset_tokens, only SHA-256(token) is stored so a table dump
-- cannot be replayed. A user can hold one row per signed-in device; logout
-- deletes that row, and expired rows are rejected by ApiTokenService.
CREATE TABLE api_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    token_hash   VARCHAR(64)  NOT NULL,
    device_name  VARCHAR(100),
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMP,
    expires_at   TIMESTAMP    NOT NULL,
    CONSTRAINT fk_api_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_api_tokens_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_api_tokens_user ON api_tokens (user_id);
