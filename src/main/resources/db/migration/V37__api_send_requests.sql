-- Idempotency keys for /api/v1 sends (docs/API.md §5.19).
--
-- A row is claimed (completed_at NULL) before SMTP runs and completed with
-- the recorded message once it is stored; a failed send deletes its row. A
-- row left unfinished means the mail may have gone out, so retries with that
-- key are refused until the 24-hour expiry. No foreign keys to the message or
-- thread: a replay returns the original ids even if they were deleted since.
CREATE TABLE api_send_requests (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL,
    idempotency_key   VARCHAR(64)  NOT NULL,
    fingerprint       VARCHAR(64)  NOT NULL,
    created_at        TIMESTAMP    NOT NULL,
    completed_at      TIMESTAMP,
    conversation_key  VARCHAR(64),
    thread_id         BIGINT,
    message_id        BIGINT,
    CONSTRAINT fk_api_send_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_api_send_requests_user_key UNIQUE (user_id, idempotency_key)
);

CREATE INDEX idx_api_send_requests_created ON api_send_requests (created_at);
