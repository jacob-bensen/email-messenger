-- Idempotency keys for the mobile send endpoints (docs/API.md §5.8a).
--
-- A row is claimed (status PENDING) before the email goes out and completed
-- with the recorded message once it is stored, so a retry with the same key
-- returns the first result instead of sending again. request_hash pins the
-- key to one request body. Rows older than 24 hours are pruned on the next
-- claim by the same user.
CREATE TABLE api_send_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    idempotency_key  VARCHAR(64)  NOT NULL,
    request_hash     VARCHAR(64)  NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    conversation_key VARCHAR(64),
    thread_id        BIGINT,
    message_id       BIGINT,
    created_at       TIMESTAMP    NOT NULL,
    completed_at     TIMESTAMP,
    CONSTRAINT fk_api_send_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_api_send_requests_user_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_api_send_requests_status CHECK (status IN ('PENDING', 'COMPLETED'))
);

CREATE INDEX idx_api_send_requests_user_created ON api_send_requests (user_id, created_at);
