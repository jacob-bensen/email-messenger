-- Idempotency keys for the /api/v1 send endpoints (docs/API.md §5.8.1).
--
-- A row is claimed (completed_at NULL) before the SMTP send and completed with
-- the response afterwards, so a client retry with the same key replays the
-- stored response instead of emailing twice. thread_id / message_id are plain
-- values, not foreign keys: a replay must still answer after the mailbox that
-- holds the message was removed.
CREATE TABLE api_send_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    idempotency_key  VARCHAR(100) NOT NULL,
    request_hash     VARCHAR(64)  NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    completed_at     TIMESTAMP,
    conversation_key VARCHAR(64),
    thread_id        BIGINT,
    message_id       BIGINT,
    CONSTRAINT fk_api_send_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_api_send_requests_user_key UNIQUE (user_id, idempotency_key)
);

CREATE INDEX idx_api_send_requests_created ON api_send_requests (created_at);
