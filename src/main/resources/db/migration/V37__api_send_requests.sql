-- Idempotency keys for the mobile client's sends (docs/API.md §5.8.1).
--
-- One row per (user, Idempotency-Key). completed_at is null while the send
-- is in flight, or forever when it ended in an unexpected error after which
-- the server cannot tell whether SMTP accepted the message; retries then get
-- 409 send_in_progress instead of a second send. Rows older than 24 hours
-- are replaced on the next use of the same key.
CREATE TABLE api_send_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    idempotency_key  VARCHAR(100) NOT NULL,
    request_hash     VARCHAR(64)  NOT NULL,
    conversation_key VARCHAR(64),
    thread_id        BIGINT,
    message_id       BIGINT,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at     TIMESTAMP,
    CONSTRAINT fk_api_send_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_api_send_requests_user_key UNIQUE (user_id, idempotency_key)
);
