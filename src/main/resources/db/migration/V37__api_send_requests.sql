-- Idempotency keys for the mobile API's send endpoints (docs/API.md §5.8.1).
--
-- A row is claimed (PENDING) before the SMTP send and completed (DONE) with
-- the recorded message once it is stored. Failed sends delete their row so
-- the key can be retried; a row left PENDING means the outcome is unknown
-- and further retries are refused rather than risk a second email.
CREATE TABLE api_send_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    idempotency_key  VARCHAR(100) NOT NULL,
    fingerprint      VARCHAR(64)  NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    conversation_key VARCHAR(64),
    thread_id        BIGINT,
    message_id       BIGINT,
    created_at       TIMESTAMP    NOT NULL,
    CONSTRAINT fk_api_send_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_api_send_requests_user_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_api_send_requests_status CHECK (status IN ('PENDING', 'DONE'))
);
