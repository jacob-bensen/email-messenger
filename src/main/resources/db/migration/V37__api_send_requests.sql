-- Idempotency keys for API sends (docs/API.md §5.8.1).
--
-- A row is claimed before the mail is sent and completed with the recorded
-- message afterwards. A row that stays uncompleted means the send is still
-- running or its outcome is unknown, so retries get 409 instead of a resend.
CREATE TABLE api_send_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    idempotency_key  VARCHAR(100) NOT NULL,
    request_hash     VARCHAR(64)  NOT NULL,
    conversation_key VARCHAR(64),
    thread_id        BIGINT,
    message_id       BIGINT,
    created_at       TIMESTAMP    NOT NULL,
    completed_at     TIMESTAMP,
    CONSTRAINT fk_api_send_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_api_send_requests_user_key UNIQUE (user_id, idempotency_key)
);

CREATE INDEX idx_api_send_requests_created ON api_send_requests (created_at);
