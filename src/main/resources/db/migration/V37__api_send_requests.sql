-- Idempotency keys for /api/v1 sends (docs/API.md §5.8, §5.9).
--
-- A row is claimed (completed_at NULL) before the SMTP send and completed with
-- the recorded message once the send succeeds; a failed send deletes it so a
-- retry can send again. thread_id / message_id have no foreign keys: a replay
-- returns the original ids even if that message was later deleted.
CREATE TABLE api_send_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    idempotency_key  VARCHAR(64)  NOT NULL,
    request_hash     VARCHAR(64)  NOT NULL,
    claimed_at       TIMESTAMP    NOT NULL,
    completed_at     TIMESTAMP,
    conversation_key VARCHAR(64),
    thread_id        BIGINT,
    message_id       BIGINT,
    CONSTRAINT fk_api_send_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_api_send_requests_user_key UNIQUE (user_id, idempotency_key)
);

CREATE INDEX idx_api_send_requests_claimed_at ON api_send_requests (claimed_at);
